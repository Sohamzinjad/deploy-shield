"""
collect_traffic.py
==================
Captures attack traffic generated by sqlmap / OWASP ZAP against the
sample-app running through the DeployShield gateway, labels each
request, and saves an eval_dataset.csv for independent evaluation.

Usage (run with the full stack up):
    python evaluation/collect_traffic.py --target http://localhost:8000/apps/<APP_ID>

Prerequisites:
    pip install requests
    sqlmap must be on PATH  (https://sqlmap.org)
    Optional: zaproxy Python SDK  (pip install python-owasp-zap-v2.4)
"""
import argparse
import csv
import json
import threading
import time
from http.server import BaseHTTPRequestHandler, HTTPServer
from typing import List, Dict
import subprocess
import os
import sys

CAPTURED: List[Dict] = []
CAPTURE_LOCK = threading.Lock()


class CaptureHandler(BaseHTTPRequestHandler):
    """Minimal proxy that records every request before forwarding."""

    def do_ANY(self):
        length = int(self.headers.get('Content-Length', 0))
        body = self.rfile.read(length).decode('utf-8', errors='replace') if length else ''
        entry = {
            'method': self.command,
            'url': self.path,
            'headers': dict(self.headers),
            'body': body,
            'label': self.server.current_label,
        }
        with CAPTURE_LOCK:
            CAPTURED.append(entry)
        self.send_response(200)
        self.end_headers()

    do_GET = do_POST = do_PUT = do_DELETE = do_ANY

    def log_message(self, fmt, *args):
        pass  # suppress console noise


class LabeledCapture(HTTPServer):
    def __init__(self, *args, **kwargs):
        self.current_label = 'benign'
        super().__init__(*args, **kwargs)


def clean_proxy_env():
    """Force the recording proxy: strip no_proxy so urllib and child tools
    (e.g. sqlmap) route through the capture server even for localhost targets."""
    os.environ.pop('no_proxy', None)
    os.environ.pop('NO_PROXY', None)


def run_sqlmap(target: str, capture_port: int, env: dict | None = None):
    """Run sqlmap with a proxy pointing at our capture server."""
    proxy = f"http://127.0.0.1:{capture_port}"
    cmd = [
        'sqlmap', '-u', f"{target}?id=1",
        '--proxy', proxy,
        '--batch', '--level=3', '--risk=2',
        '--technique=BEUST',
        '--output-dir=/tmp/sqlmap_out'
    ]
    print(f"[sqlmap] Running: {' '.join(cmd)}")
    try:
        subprocess.run(cmd, timeout=120, capture_output=True, env=env)
    except FileNotFoundError:
        print("[WARN] sqlmap not found on PATH — skipping sqlmap phase.")
    except subprocess.TimeoutExpired:
        print("[sqlmap] Timeout reached (120s).")


def generate_benign_traffic(target: str, capture_port: int):
    """Send a batch of realistic benign requests through the capture proxy."""
    import urllib.request

    benign_paths = [
        '/products?category=electronics&sort=price&page=1',
        '/blog/2026/best-laptops-for-students',
        '/search?q=Tom+%27s+Diner',
        '/api/users/42/profile',
        '/contact?name=Jane+Doe&email=jane%40example.com',
        "/about",
        '/items?q=O%27Brien%27s+cafe&limit=20',
        '/docs/select-the-best-laptop',
        '/search?q=cat+food&brand=whiskas',
        '/products/1234/reviews?min=3&max=5',
    ]
    proxy_handler = urllib.request.ProxyHandler({'http': f'http://127.0.0.1:{capture_port}'})
    opener = urllib.request.build_opener(proxy_handler)
    for path in benign_paths:
        try:
            opener.open(f"{target}{path}", timeout=5)
        except Exception:
            pass
    print(f"[benign] Sent {len(benign_paths)} benign requests.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--target', default='http://localhost:8000/apps/sample',
                        help='Gateway URL for the sample app')
    parser.add_argument('--out', default='evaluation/eval_dataset.csv')
    parser.add_argument('--capture-port', type=int, default=9999)
    args = parser.parse_args()

    # Ensure the recording proxy is actually used by every client below.
    clean_proxy_env()
    child_env = {k: v for k, v in os.environ.items()}  # stripped of no_proxy/NO_PROXY

    # Start capture proxy
    server = LabeledCapture(('127.0.0.1', args.capture_port), CaptureHandler)
    t = threading.Thread(target=server.serve_forever, daemon=True)
    t.start()
    print(f"[capture] Listening on port {args.capture_port}")
    time.sleep(0.5)

    # Phase 1: benign traffic
    server.current_label = 'benign'
    generate_benign_traffic(args.target, args.capture_port)

    # Phase 2: SQLi via sqlmap
    server.current_label = 'sqli'
    run_sqlmap(args.target, args.capture_port, env=child_env)

    server.shutdown()

    # Write CSV
    os.makedirs(os.path.dirname(args.out) or '.', exist_ok=True)
    with open(args.out, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['method', 'url', 'headers', 'body', 'label'])
        writer.writeheader()
        for row in CAPTURED:
            row['headers'] = json.dumps(row['headers'])
            writer.writerow(row)

    print(f"\n[done] {len(CAPTURED)} requests saved to {args.out}")
    from collections import Counter
    print("Label counts:", Counter(r['label'] for r in CAPTURED))


if __name__ == '__main__':
    main()
